// Scheduling weights from hosted shard receipts (`gh run download RUN -p 'shard-*' -D DIR`): `refresh` rewrites
// ci-test-durations.json, `check` runs the drift guard (the CI drift job, or offline) and exits 1 on drift.
import { appendFileSync, existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DURATION_DRIFT, durationDrift, inventoryDigest, observedDurations } from './ci-test-plan.mjs';

const weightsPath = fileURLToPath(new URL('./ci-test-durations.json', import.meta.url));

export function readReceipts(directories) {
  const receipts = [];
  for (const directory of directories) {
    const found = existsSync(join(directory, 'receipt.json')) ? [directory]
      : readdirSync(directory).map(name => join(directory, name)).filter(path => existsSync(join(path, 'receipt.json')));
    if (!found.length) throw new Error(`No shard receipt under ${directory}`);
    for (const path of found.sort()) receipts.push(JSON.parse(readFileSync(join(path, 'receipt.json'), 'utf8')));
  }
  return receipts;
}

// Every receipt must describe one inventory, and together they must observe all of it.
// `complete: false` accepts the receipts of a run whose shards were cut at the job limit (the drift job); refresh needs every file.
export function receiptInventory(receipts, { complete = true } = {}) {
  const digests = new Set(receipts.map(receipt => receipt.inventoryDigest));
  const files = [...new Set(receipts.flatMap(receipt => (receipt.files ?? []).map(row => row.file)))].sort();
  if (digests.size !== 1 || (complete && inventoryDigest(files) !== [...digests][0])) throw new Error('Receipts do not cover one complete inventory');
  return { digest: [...digests][0], files };
}

export function refreshedWeights(receipts) {
  const inventory = receiptInventory(receipts), observed = observedDurations(receipts);
  const attempts = new Map();
  for (const receipt of receipts) {
    const key = `${receipt.runId}/${receipt.attempt}`;
    const entry = attempts.get(key) ?? { runId: Number(receipt.runId), runAttempt: Number(receipt.attempt), headSha: receipt.sha, receipts: {} };
    entry.receipts[`node${receipt.node}`] = (entry.receipts[`node${receipt.node}`] ?? 0) + 1;
    attempts.set(key, entry);
  }
  const runAttempts = [...attempts.values()].sort((a, b) => a.runId - b.runId || a.runAttempt - b.runAttempt);
  const weighted = inventory.files.filter(file => observed[file] > 0);
  return { schemaVersion: 1, source: {
    kind: 'hosted per-file wall time from shard receipt.json artifacts (Vitest reporter durationMs), maximum across every given run, Node job and shard on two forks, rounded up to integer ms; generated by scripts/ci-test-weights.mjs refresh; scheduling weights, not an end-to-end performance claim',
    runs: [...new Set(runAttempts.map(entry => entry.runId))], runAttempts,
    inventoryDigest: inventory.digest, inventoryFiles: inventory.files.length, files: weighted.length,
    medianFallbackFiles: inventory.files.filter(file => !(observed[file] > 0)),
    note: 'headSha is the commit each receipt tested (a pull_request run tests its merge commit). Zero-duration all-skipped files have no positive weight, use the partitionTests observed-median fallback and are not drift. Failed-file timing is retained as cost, not acceptance.',
  }, durationMs: Object.fromEntries(weighted.map(file => [file, observed[file]])) };
}

// One line per finding category; GitHub shows `::warning` lines as run annotations.
export function driftReport(result, limits = DURATION_DRIFT) {
  const lines = [];
  if (result.slow.length) lines.push(`${result.slow.length} file(s) ran over ${limits.maxRatio}x their scheduling weight: `
    + result.slow.map(row => `${row.file} ${(row.observedMs / 1000).toFixed(1)} s vs ${(row.weightMs / 1000).toFixed(1)} s`).join('; '));
  if (result.unweighted.length > limits.maxUnweightedFiles) lines.push(`${result.unweighted.length} file(s) ran without a scheduling weight`
    + ` (allowed ${limits.maxUnweightedFiles}): ${result.unweighted.slice(0, 10).join('; ')}${result.unweighted.length > 10 ? '; ...' : ''}`);
  return lines.map(line => `${line}. Refresh scripts/ci-test-durations.json with scripts/ci-test-weights.mjs.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [command, ...rest] = process.argv.slice(2);
  const option = rest.indexOf('--durations');
  const durationsPath = option >= 0 ? rest[option + 1] : weightsPath;
  const directories = option >= 0 ? rest.filter((_, index) => index !== option && index !== option + 1) : rest;
  if (!['refresh', 'check'].includes(command) || !directories.length || !durationsPath) {
    throw new Error('Usage: ci-test-weights.mjs refresh|check [--durations PATH] ARTIFACT_DIR...');
  }
  const receipts = readReceipts(directories);
  if (command === 'refresh') {
    const weights = refreshedWeights(receipts);
    writeFileSync(durationsPath, JSON.stringify(weights, null, 2) + '\n');
    console.log(`Weighted ${weights.source.files}/${weights.source.inventoryFiles} files from ${receipts.length} receipts`);
  } else {
    const durations = JSON.parse(readFileSync(durationsPath, 'utf8')).durationMs;
    const result = durationDrift(receiptInventory(receipts, { complete: false }).files, observedDurations(receipts), durations);
    const annotate = process.env.GITHUB_ACTIONS === 'true' ? '::warning file=scripts/ci-test-durations.json,title=CI duration weight drift::' : '';
    for (const line of driftReport(result)) console.log(`${annotate}${line}`);
    const summary = `Duration drift: ${result.drifted ? 'DRIFT' : 'none'} (${result.slow.length} slow, ${result.unweighted.length} unweighted)`;
    console.log(summary);
    if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, `${summary}\n`);
    process.exitCode = result.drifted ? 1 : 0;
  }
}
